test.describe('Plan & work: drafting', () => {
  test('a manager drafts the first plan and sees what Odin left out', async ({ page }, testInfo) => {
    const { plans } = await open(page, planPath, { latest: 'none' });
    const panel = planPanel(page);
    await expect(panel.getByText('No plan yet')).toBeVisible();
    await expectNoSeriousIssues(page, testInfo, 'plan-empty');
    await panel.getByRole('button', { name: 'Draft plan' }).click();
    await expect(panel.getByRole('heading', { name: 'Experience plan · v1' })).toBeFocused();
    await expect(panel).toContainText('Draft · not approved yet');
    await expect(panel.getByRole('status')).toHaveText('Odin left out 1 item that didn’t cite a recorded decision and removed 1 citation to decisions a plan can’t build on.');
    await expect(page.getByRole('status').filter({ hasText: 'Drafted Experience plan v1 from the track’s decisions.' })).toBeVisible();
    expect(plans.calls.filter((call) => call.path === '/experience/draft')).toHaveLength(1);
    await expect(page.locator('.rq-workspace')).not.toContainText(AI_LABELS);
  });

  for (const { mode, message, retry } of [
    { message: 'Odin can’t draft plans because no AI provider is set up for this workspace. A workspace admin can add one in the AI settings.', mode: 'ai_not_configured', retry: false },
    { message: 'Odin couldn’t draft the plan, so nothing changed. Try again.', mode: 'ai_request_failed', retry: true },
    { message: 'Odin’s draft had no acceptance criteria that cite a recorded decision, so nothing was saved. Try again.', mode: 'plan_output_uncited', retry: true },
    { message: 'This track has no recorded decisions or accepted preferences yet. Record some in the Decide stage, then draft the plan. Go to Decide', mode: 'no_decisions', retry: false },
  ]) {
    test(`a failed draft (${mode}) explains itself and keeps the current plan`, async ({ page }) => {
      const { plans } = await open(page, planPath, { adjust: (scenario) => { scenario.plansState.draftMode = mode; }, latest: 'approved' });
      const panel = planPanel(page);
      await panel.getByRole('button', { name: 'Redraft from decisions' }).click();
      const alert = panel.getByRole('alert');
      await expect(alert).toContainText(message);
      await expect(alert.getByRole('button', { name: 'Try again' })).toHaveCount(retry ? 1 : 0);
      await expect(panel.getByRole('heading', { name: 'Experience plan · v2' })).toBeVisible();
      if (mode === 'no_decisions') await expect(alert.getByRole('link', { name: 'Go to Decide' })).toHaveAttribute('href', /\/experience\/decide$/);
      if (retry) {
        plans.state.draftMode = 'ok';
        await alert.getByRole('button', { name: 'Try again' }).click();
        await expect(panel.getByRole('heading', { name: 'Experience plan · v3' })).toBeVisible();
      }
    });
  }
});

