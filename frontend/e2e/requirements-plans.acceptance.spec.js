import AxeBuilder from '@axe-core/playwright';
import { expect, test } from '@playwright/test';

import { installRequirementsApi } from './fixtures/requirements-api.js';
import { installRequirementsPlansApi, plansScenario } from './fixtures/requirements-plans-api.js';
import { authenticateSyntheticUser, installSyntheticApi, syntheticProject } from './fixtures/synthetic-api.js';
import { settleForAxe } from './fixtures/axe-settle.js';

// Plan & work: the decisions a plan builds on, the plan with its owner and no AI-drafted
// tag, draft and redraft with every error the stage explains, editing with the optimistic
// revision, approving (decision rights only), proposing work, and who sees the AI
// Workspace review link. Synthetic API only.
const base = `projects/${syntheticProject.id}/requirements`;
const planPath = `${base}/experience/plan`;
const wcagTags = ['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa'];
const AI_LABELS = /AI proposal|AI-drafted|drafted by AI|generated by AI|AI draft/i;

async function open(page, target = planPath, { adjust = () => {}, ...options } = {}) {
  const scenario = plansScenario(options);
  adjust(scenario);
  const api = await installSyntheticApi(page);
  const requirements = await installRequirementsApi(page, scenario);
  const plans = await installRequirementsPlansApi(page, requirements);
  const pageErrors = [];
  page.on('pageerror', (error) => pageErrors.push(error.message));
  await authenticateSyntheticUser(page);
  await page.goto(target);
  return { api, pageErrors, plans, requirements };
}

function as(role) {
  return (scenario) => {
    scenario.canDecide = role === 'manager';
    scenario.projectRole = role;
  };
}

async function expectNoSeriousIssues(page, testInfo, name) {
  await page.evaluate(() => window.scrollTo(0, 0));
  await settleForAxe(page);
  const results = await new AxeBuilder({ page }).include('.rq-workspace').withTags(wcagTags).analyze();
  await testInfo.attach(`axe-${name}.json`, { body: JSON.stringify(results.violations, null, 2), contentType: 'application/json' });
  const serious = results.violations
    .filter((violation) => ['serious', 'critical'].includes(violation.impact))
    .map((violation) => `${violation.id}: ${violation.nodes.map((node) => node.target.join(' ')).join(', ')}`);
  expect(serious, name).toEqual([]);
}

