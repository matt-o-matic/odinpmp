test.describe('Plan & work: live updates and phones', () => {
  test('an approval elsewhere refreshes the plan without reloading', async ({ page }) => {
    const { plans, requirements } = await open(page, planPath, { adjust: (scenario) => { scenario.liveEvents = true; } });
    const panel = planPanel(page);
    await expect(panel).toContainText('Draft · not approved yet');
    const draft = plans.state.plans.find((entry) => entry.id === 'plan-3');
    Object.assign(draft, { approvedAt: new Date().toISOString(), owner: { id: 'user-morgan', name: 'Morgan Lee' }, revision: 2, status: 'approved' });
    Object.assign(plans.state.plans.find((entry) => entry.id === 'plan-2'), { status: 'superseded' });
    plans.syncShared();
    requirements.pushEvent({ data: { planId: 'plan-3', reason: 'plan-approved', track: 'experience', version: 3 }, type: 'requirements.plans.invalidated' });
    await expect(panel).toContainText('Owner: Morgan Lee · approved today', { timeout: 10_000 });
  });

  test('the plan stage fits a phone and passes axe in dark mode', async ({ page }, testInfo) => {
    await open(page, planPath, { latest: 'approved' });
    await expect(planPanel(page).getByRole('heading', { name: 'Experience plan · v2' })).toBeVisible();
    const overflow = await page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth);
    expect(overflow).toBeLessThanOrEqual(1);
    await page.evaluate(() => document.documentElement.classList.add('dark'));
    await expectNoSeriousIssues(page, testInfo, 'plan-dark');
  });
});
